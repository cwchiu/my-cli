const (
	defaultYouTubeTimeout       = 30 * time.Second
	maxYouTubeResponseSize      = 10 << 20
	defaultYouTubeLanguage      = "en"
	youtubeTranscriptOutputText = "text"
	youtubeTranscriptOutputJSON = "json"
	youtubeAndroidClientVersion = "19.29.37"
	youtubeTranscriptPageURL    = "https://www.youtube.com/watch"
	youtubeTranscriptAPIURL     = "https://www.youtube.com/youtubei/v1/get_transcript?prettyPrint=false"
	youtubeBrowserUserAgent     = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
	youtubeAndroidUserAgent     = "com.google.android.youtube/19.29.37 (Linux; U; Android 11) gzip"
)

var (
	youtubeVideoIDPattern     = regexp.MustCompile(`^[A-Za-z0-9_-]{11}$`)
	youtubeVisitorDataPattern = regexp.MustCompile(`"visitorData":"([^"]+)"`)
)

type youtubeTranscriptConfig struct {
	language     string
	timeout      time.Duration
	outputFormat string
}

type youtubeEndpoints struct {
	pageURL       string
	transcriptURL string
}

type youtubeCaptionTrack struct {
	LanguageCode    string `json:"languageCode"`
	Name            string `json:"name"`
	IsAutoGenerated bool   `json:"isAutoGenerated"`
}

type youtubeTranscriptLine struct {
	Text  string  `json:"text"`
	Start float64 `json:"start"`
	Dur   float64 `json:"dur"`
}

type youtubeTranscriptResult struct {
	Lines              []youtubeTranscriptLine `json:"lines"`
	RequestedLang      string                  `json:"requestedLang"`
	ActualLang         string                  `json:"actualLang"`
	AvailableLanguages []youtubeCaptionTrack   `json:"availableLanguages"`
}

type youtubePageData struct {
	visitorData        string
	availableLanguages []youtubeCaptionTrack
}

type youtubeTrackName struct {
	SimpleText string `json:"simpleText"`
	Runs       []struct {
		Text string `json:"text"`
	} `json:"runs"`
}

type youtubeRawCaptionTrack struct {
	LanguageCode string           `json:"languageCode"`
	Name         youtubeTrackName `json:"name"`
	Kind         string           `json:"kind"`
}

type youtubeTranscriptAPIError struct {
	Code    json.RawMessage `json:"code"`
	Message string          `json:"message"`
}

type youtubeTranscriptAPIResponse struct {
	Error   *youtubeTranscriptAPIError `json:"error"`
	Actions []youtubeTranscriptAction  `json:"actions"`
}

type youtubeTranscriptAction struct {
	UpdateEngagementPanelAction *youtubeEngagementPanelAction `json:"updateEngagementPanelAction"`
	ElementsCommand             *youtubeElementsCommand       `json:"elementsCommand"`
}

type youtubeEngagementPanelAction struct {
	Content struct {
		TranscriptRenderer struct {
			Content struct {
				TranscriptSearchPanelRenderer struct {
					Body struct {
						TranscriptSegmentListRenderer struct {
							InitialSegments []youtubeRawTranscriptSegment `json:"initialSegments"`
						} `json:"transcriptSegmentListRenderer"`
					} `json:"body"`
				} `json:"transcriptSearchPanelRenderer"`
			} `json:"content"`
		} `json:"transcriptRenderer"`
	} `json:"content"`
}

type youtubeElementsCommand struct {
	TransformEntityCommand struct {
		Arguments struct {
			TransformTranscriptSegmentListArguments struct {
				Overwrite struct {
					InitialSegments []youtubeRawTranscriptSegment `json:"initialSegments"`
				} `json:"overwrite"`
			} `json:"transformTranscriptSegmentListArguments"`
		} `json:"arguments"`
	} `json:"transformEntityCommand"`
}

type youtubeRawTranscriptSegment struct {
	TranscriptSegmentRenderer *struct {
		StartMS json.RawMessage `json:"startMs"`
		EndMS   json.RawMessage `json:"endMs"`
		Snippet struct {
			Runs []struct {
				Text string `json:"text"`
			} `json:"runs"`
			ElementsAttributedString struct {
				Content string `json:"content"`
			} `json:"elementsAttributedString"`
		} `json:"snippet"`
	} `json:"transcriptSegmentRenderer"`
}

func newYouTubeTranscriptCmd() *cobra.Command {
	return newYouTubeTranscriptCmdWithEndpoints(youtubeEndpoints{
		pageURL:       youtubeTranscriptPageURL,
		transcriptURL: youtubeTranscriptAPIURL,
	})
}

func newYouTubeTranscriptCmdWithEndpoints(endpoints youtubeEndpoints) *cobra.Command {
	var raw youtubeTranscriptConfig

	validateArgs := cobra.MatchAll(cobra.ExactArgs(1), func(_ *cobra.Command, args []string) error {
		_, err := parseYouTubeVideoID(args[0])

		return err
	})

	cmd := &cobra.Command{
		Use:   "youtube-transcript URL",
		Short: "Fetch a YouTube video's transcript",
		Long: `Fetch caption segments for a YouTube video and print their text with
timestamps. The requested language falls back to English, then the first
available caption language, when necessary.`,
		Example: `  my-cli youtube-transcript https://www.youtube.com/watch?v=dQw4w9WgXcQ
  my-cli youtube-transcript https://youtu.be/dQw4w9WgXcQ --lang zh-Hant
  my-cli youtube-transcript https://youtu.be/dQw4w9WgXcQ --output json`,
		Args: wrapUsage(validateArgs),
		RunE: func(cmd *cobra.Command, args []string) error {
			config, err := resolveYouTubeTranscriptConfig(raw)
			if err != nil {
				return err
			}

			videoID, err := parseYouTubeVideoID(args[0])
			if err != nil {
				return err
			}

			result, err := fetchYouTubeTranscript(cmd.Context(), videoID, config, endpoints)
			if err != nil {
				return err
			}

			return renderYouTubeTranscript(cmd.OutOrStdout(), config.outputFormat, result)
		},
	}

	cmd.Flags().StringVar(&raw.language, "lang", defaultYouTubeLanguage, "preferred caption language code")
	cmd.Flags().DurationVar(&raw.timeout, "timeout", defaultYouTubeTimeout, "total request timeout")
	cmd.Flags().StringVarP(
		&raw.outputFormat,
		"output",
		"o",
		youtubeTranscriptOutputText,
		"output format (text|json)",
	)
	_ = cmd.RegisterFlagCompletionFunc("output", func(
		_ *cobra.Command, _ []string, _ string,
	) ([]string, cobra.ShellCompDirective) {
		return []string{youtubeTranscriptOutputText, youtubeTranscriptOutputJSON},
			cobra.ShellCompDirectiveNoFileComp
	})

	return cmd
}

func resolveYouTubeTranscriptConfig(raw youtubeTranscriptConfig) (youtubeTranscriptConfig, error) {
	if raw.timeout <= 0 {
		return youtubeTranscriptConfig{}, fmt.Errorf("timeout must be positive, got %s", raw.timeout)
	}

	if !validYouTubeLanguage(raw.language) {
		return youtubeTranscriptConfig{}, fmt.Errorf("invalid language code %q", raw.language)
	}

	switch raw.outputFormat {
	case youtubeTranscriptOutputText, youtubeTranscriptOutputJSON:
	default:
		return youtubeTranscriptConfig{}, fmt.Errorf("unsupported output format %q", raw.outputFormat)
	}

	return raw, nil
}

func validYouTubeLanguage(language string) bool {
	if language == "" {
		return false
	}

	for part := range strings.SplitSeq(language, "-") {
		if part == "" {
			return false
		}

		for _, character := range part {
			if !isYouTubeLanguageCharacter(character) {
				return false
			}
		}
	}

	return true
}

func isYouTubeLanguageCharacter(character rune) bool {
	isLower := character >= 'a' && character <= 'z'
	isUpper := character >= 'A' && character <= 'Z'
	isDigit := character >= '0' && character <= '9'

	return isLower || isUpper || isDigit
}

func parseYouTubeVideoID(value string) (string, error) {
	parsed, err := url.Parse(value)
	if err != nil {
		return "", invalidYouTubeURL(value)
	}

	if parsed.Scheme != "https" && parsed.Scheme != "http" {
		return "", invalidYouTubeURL(value)
	}

	host := strings.ToLower(parsed.Hostname())
	switch host {
	case "youtu.be", "www.youtu.be":
		return parseYouTubeShortLink(parsed.Path, value)
	case "youtube.com", "www.youtube.com", "m.youtube.com", "music.youtube.com",
		"youtube-nocookie.com", "www.youtube-nocookie.com":
		return parseYouTubeStandardLink(parsed, value)
	}

	return "", invalidYouTubeURL(value)
}

func parseYouTubeShortLink(path, originalURL string) (string, error) {
	videoID := strings.Trim(path, "/")
	if strings.Contains(videoID, "/") || !youtubeVideoIDPattern.MatchString(videoID) {
		return "", invalidYouTubeURL(originalURL)
	}

	return videoID, nil
}

func parseYouTubeStandardLink(parsed *url.URL, originalURL string) (string, error) {
	videoID := parsed.Query().Get("v")
	if youtubeVideoIDPattern.MatchString(videoID) {
		return videoID, nil
	}

	pathParts := strings.Split(strings.Trim(parsed.Path, "/"), "/")
	isVideoPath := len(pathParts) == 2 &&
		(pathParts[0] == "shorts" || pathParts[0] == "embed" || pathParts[0] == "live")

	if isVideoPath && youtubeVideoIDPattern.MatchString(pathParts[1]) {
		return pathParts[1], nil
	}

	return "", invalidYouTubeURL(originalURL)
}

func invalidYouTubeURL(value string) error {
	return fmt.Errorf("invalid youtube URL %q", value)
}

func fetchYouTubeTranscript(
	ctx context.Context,
	videoID string,
	config youtubeTranscriptConfig,
	endpoints youtubeEndpoints,
) (youtubeTranscriptResult, error) {
	client := &http.Client{Timeout: config.timeout}

	pageData, err := fetchYouTubePageData(ctx, client, videoID, endpoints.pageURL)
	if err != nil {
		return youtubeTranscriptResult{}, err
	}

	actualLanguage := selectYouTubeLanguage(config.language, pageData.availableLanguages)

	payload, err := buildYouTubeTranscriptRequest(videoID, actualLanguage, pageData.visitorData)
	if err != nil {
		return youtubeTranscriptResult{}, fmt.Errorf("encode transcript request: %w", err)
	}

	request, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoints.transcriptURL, bytes.NewReader(payload))
	if err != nil {
		return youtubeTranscriptResult{}, fmt.Errorf("create transcript request: %w", err)
	}

	request.Header.Set("Content-Type", "application/json")
	request.Header.Set("Origin", "https://www.youtube.com")
	request.Header.Set("User-Agent", youtubeAndroidUserAgent)

	body, err := doYouTubeRequest(client, request)
	if err != nil {
		return youtubeTranscriptResult{}, fmt.Errorf("fetch youtube transcript: %w", err)
	}

	result, err := parseYouTubeTranscriptResponse(body, config.language, actualLanguage, pageData.availableLanguages)
	if err != nil {
		return youtubeTranscriptResult{}, err
	}

	return result, nil
}

func fetchYouTubePageData(
	ctx context.Context,
	client *http.Client,
	videoID string,
	pageEndpoint string,
) (youtubePageData, error) {
	pageURL, err := url.Parse(pageEndpoint)
	if err != nil {
		return youtubePageData{}, fmt.Errorf("parse youtube page URL: %w", err)
	}

	query := pageURL.Query()
	query.Set("v", videoID)
	pageURL.RawQuery = query.Encode()

	request, err := http.NewRequestWithContext(ctx, http.MethodGet, pageURL.String(), nil)
	if err != nil {
		return youtubePageData{}, fmt.Errorf("create youtube page request: %w", err)
	}

	request.Header.Set("Accept-Language", "en-US,en;q=0.9")
	request.Header.Set("User-Agent", youtubeBrowserUserAgent)

	body, err := doYouTubeRequest(client, request)
	if err != nil {
		return youtubePageData{}, fmt.Errorf("fetch youtube video page: %w", err)
	}

	pageData := youtubePageData{
		availableLanguages: []youtubeCaptionTrack{},
	}
	if match := youtubeVisitorDataPattern.FindSubmatch(body); len(match) == 2 {
		pageData.visitorData = string(match[1])
	}

	trackJSON, err := extractYouTubeJSONArray(body, `"captionTracks"`)
	if err != nil {
		return youtubePageData{}, fmt.Errorf("find youtube caption tracks: %w", err)
	}

	if len(trackJSON) == 0 {
		return pageData, nil
	}

	var rawTracks []youtubeRawCaptionTrack
	if err := json.Unmarshal(trackJSON, &rawTracks); err != nil {
		return youtubePageData{}, fmt.Errorf("decode youtube caption tracks: %w", err)
	}

	for _, track := range rawTracks {
		if track.LanguageCode == "" {
			continue
		}

		name := track.Name.SimpleText
		if name == "" && len(track.Name.Runs) > 0 {
			name = track.Name.Runs[0].Text
		}

		if name == "" {
			name = track.LanguageCode
		}

		pageData.availableLanguages = append(pageData.availableLanguages, youtubeCaptionTrack{
			LanguageCode:    track.LanguageCode,
			Name:            name,
			IsAutoGenerated: track.Kind == "asr",
		})
	}

	return pageData, nil
}

func extractYouTubeJSONArray(source []byte, marker string) ([]byte, error) {
	markerIndex := bytes.Index(source, []byte(marker))
	if markerIndex < 0 {
		return nil, nil
	}

	start := bytes.IndexByte(source[markerIndex+len(marker):], '[')
	if start < 0 {
		return nil, errors.New("caption track list is not an array")
	}

	start += markerIndex + len(marker)

	end := findYouTubeJSONArrayEnd(source, start)
	if end < 0 {
		return nil, errors.New("unterminated caption track list")
	}

	return source[start : end+1], nil
}

func findYouTubeJSONArrayEnd(source []byte, start int) int {
	depth := 0
	inString := false
	escaped := false

	for index := start; index < len(source); index++ {
		character := source[index]

		if inString && escaped {
			escaped = false
			continue
		}

		if inString && character == '\\' {
			escaped = true
			continue
		}

		if character == '"' {
			inString = !inString
			continue
		}

		if inString {
			continue
		}

		switch character {
		case '[':
			depth++
		case ']':
			depth--
			if depth == 0 {
				return index
			}
		}
	}

	return -1
}

func selectYouTubeLanguage(requested string, available []youtubeCaptionTrack) string {
	for _, track := range available {
		if track.LanguageCode == requested {
			return requested
		}
	}

	for _, track := range available {
		if track.LanguageCode == "en" || strings.HasPrefix(track.LanguageCode, "en-") {
			return track.LanguageCode
		}
	}

	if len(available) > 0 {
		return available[0].LanguageCode
	}

	return requested
}

func buildYouTubeTranscriptRequest(videoID, language, visitorData string) ([]byte, error) {
	params := buildYouTubeTranscriptParams(videoID, language)
	request := struct {
		Context struct {
			Client struct {
				HL                string `json:"hl"`
				GL                string `json:"gl"`
				ClientName        string `json:"clientName"`
				ClientVersion     string `json:"clientVersion"`
				AndroidSDKVersion int    `json:"androidSdkVersion"`
				VisitorData       string `json:"visitorData"`
			} `json:"client"`
		} `json:"context"`
		Params string `json:"params"`
	}{}
	request.Context.Client.HL = language
	request.Context.Client.GL = "US"
	request.Context.Client.ClientName = "ANDROID"
	request.Context.Client.ClientVersion = youtubeAndroidClientVersion
	request.Context.Client.AndroidSDKVersion = 30
	request.Context.Client.VisitorData = visitorData
	request.Params = params

	body, err := json.Marshal(request)
	if err != nil {
		return nil, fmt.Errorf("marshal youtube transcript request: %w", err)
	}

	return body, nil
}

func buildYouTubeTranscriptParams(videoID, language string) string {
	inner := []byte{0x0a, 0x03, 'a', 's', 'r', 0x12}
	inner = appendYouTubeVarint(inner, uint64(len(language)))
	inner = append(inner, language...)
	inner = append(inner, 0x1a, 0x00)
	encodedLanguage := url.QueryEscape(base64.StdEncoding.EncodeToString(inner))

	const panelName = "engagement-panel-searchable-transcript-search-panel"

	outer := []byte{0x0a}

	outer = appendYouTubeVarint(outer, uint64(len(videoID)))
	outer = append(outer, videoID...)
	outer = append(outer, 0x12)
	outer = appendYouTubeVarint(outer, uint64(len(encodedLanguage)))
	outer = append(outer, encodedLanguage...)
	outer = append(outer, 0x18, 0x01, 0x2a)
	outer = appendYouTubeVarint(outer, uint64(len(panelName)))
	outer = append(outer, panelName...)
	outer = append(outer, 0x30, 0x01, 0x38, 0x01, 0x40, 0x01)

	return base64.StdEncoding.EncodeToString(outer)
}

func appendYouTubeVarint(target []byte, value uint64) []byte {
	for value > 0x7f {
		target = append(target, byte(value&0x7f)|0x80)
		value >>= 7
	}

	return append(target, byte(value))
}

func doYouTubeRequest(client *http.Client, request *http.Request) ([]byte, error) {
	response, err := client.Do(request)
	if err != nil {
		return nil, fmt.Errorf("send request: %w", err)
	}

	body, err := io.ReadAll(io.LimitReader(response.Body, maxYouTubeResponseSize+1))
	closeErr := response.Body.Close()

	if err != nil {
		return nil, fmt.Errorf("read response: %w", err)
	}

	if closeErr != nil {
		return nil, fmt.Errorf("close response body: %w", closeErr)
	}

	if response.StatusCode < http.StatusOK || response.StatusCode >= http.StatusMultipleChoices {
		return nil, fmt.Errorf("request returned status %d", response.StatusCode)
	}

	if len(body) > maxYouTubeResponseSize {
		return nil, fmt.Errorf("response exceeds %d-byte limit", maxYouTubeResponseSize)
	}

	return body, nil
}

func parseYouTubeTranscriptResponse(
	body []byte,
	requestedLanguage string,
	actualLanguage string,
	availableLanguages []youtubeCaptionTrack,
) (youtubeTranscriptResult, error) {
	var response youtubeTranscriptAPIResponse
	if err := json.Unmarshal(body, &response); err != nil {
		return youtubeTranscriptResult{}, fmt.Errorf("decode youtube transcript response: %w", err)
	}

	if response.Error != nil {
		message := response.Error.Message
		if message == "" {
			message = string(response.Error.Code)
		}

		if message == "" {
			message = "unknown api error"
		}

		return youtubeTranscriptResult{}, fmt.Errorf("youtube transcript api error: %s", message)
	}

	result := youtubeTranscriptResult{
		Lines:              []youtubeTranscriptLine{},
		RequestedLang:      requestedLanguage,
		ActualLang:         actualLanguage,
		AvailableLanguages: availableLanguages,
	}

	for _, action := range response.Actions {
		if action.UpdateEngagementPanelAction != nil {
			segments := action.UpdateEngagementPanelAction.Content.TranscriptRenderer.Content.
				TranscriptSearchPanelRenderer.Body.TranscriptSegmentListRenderer.InitialSegments

			lines, err := decodeYouTubeTranscriptSegments(segments)
			if err != nil {
				return youtubeTranscriptResult{}, err
			}

			result.Lines = append(result.Lines, lines...)
		}

		if action.ElementsCommand != nil {
			segments := action.ElementsCommand.TransformEntityCommand.Arguments.
				TransformTranscriptSegmentListArguments.Overwrite.InitialSegments

			lines, err := decodeYouTubeTranscriptSegments(segments)
			if err != nil {
				return youtubeTranscriptResult{}, err
			}

			result.Lines = append(result.Lines, lines...)
		}
	}

	if len(result.Lines) == 0 {
		return youtubeTranscriptResult{}, errors.New("no transcript available for this video")
	}

	return result, nil
}

func decodeYouTubeTranscriptSegments(
	segments []youtubeRawTranscriptSegment,
) ([]youtubeTranscriptLine, error) {
	lines := make([]youtubeTranscriptLine, 0, len(segments))
	for _, segment := range segments {
		renderer := segment.TranscriptSegmentRenderer
		if renderer == nil {
			continue
		}

		var textBuilder strings.Builder
		for _, run := range renderer.Snippet.Runs {
			textBuilder.WriteString(run.Text)
		}

		text := textBuilder.String()
		if text == "" {
			text = renderer.Snippet.ElementsAttributedString.Content
		}

		if text == "" {
			continue
		}

		startMS, err := parseYouTubeMilliseconds(renderer.StartMS)
		if err != nil {
			return nil, fmt.Errorf("parse transcript segment start: %w", err)
		}

		endMS, err := parseYouTubeMilliseconds(renderer.EndMS)
		if err != nil {
			return nil, fmt.Errorf("parse transcript segment end: %w", err)
		}

		if endMS < startMS {
			return nil, errors.New("transcript segment ends before it starts")
		}

		lines = append(lines, youtubeTranscriptLine{
			Text:  text,
			Start: float64(startMS) / 1000,
			Dur:   float64(endMS-startMS) / 1000,
		})
	}

	return lines, nil
}

func parseYouTubeMilliseconds(value json.RawMessage) (int64, error) {
	value = bytes.TrimSpace(value)
	if len(value) == 0 {
		return 0, errors.New("missing timestamp")
	}

	var raw string
	if value[0] == '"' {
		if err := json.Unmarshal(value, &raw); err != nil {
			return 0, fmt.Errorf("decode timestamp: %w", err)
		}
	} else {
		raw = string(value)
	}

	milliseconds, err := strconv.ParseInt(raw, 10, 64)
	if err != nil {
		return 0, fmt.Errorf("invalid timestamp %q", raw)
	}

	return milliseconds, nil
}

func renderYouTubeTranscript(writer io.Writer, format string, result youtubeTranscriptResult) error {
	if format == youtubeTranscriptOutputJSON {
		encoder := json.NewEncoder(writer)
		encoder.SetIndent("", "  ")

		if err := encoder.Encode(result); err != nil {
			return fmt.Errorf("write transcript json: %w", err)
		}

		return nil
	}

	for _, line := range result.Lines {
		if _, err := fmt.Fprintf(writer, "[%s] %s\n", formatYouTubeTimestamp(line.Start), line.Text); err != nil {
			return fmt.Errorf("write transcript: %w", err)
		}
	}

	return nil
}

func formatYouTubeTimestamp(seconds float64) string {
	milliseconds := int64(seconds * 1000)
	hours := milliseconds / 3_600_000
	minutes := milliseconds / 60_000 % 60
	wholeSeconds := milliseconds / 1000 % 60
	fraction := milliseconds % 1000

	return fmt.Sprintf("%02d:%02d:%02d.%03d", hours, minutes, wholeSeconds, fraction)
}
